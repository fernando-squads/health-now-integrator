package br.com.bancadoingresso.integrator.model;

public class SituacaoLocalidade {
	private Long coSituacaoLocalidade;
	private String noSituacaoLocalidade;
	private String sgSituacaoLocalidade;
	
	public SituacaoLocalidade() {
		
	}

	public Long getCoSituacaoLocalidade() {
		return coSituacaoLocalidade;
	}

	public void setCoSituacaoLocalidade(Long coSituacaoLocalidade) {
		this.coSituacaoLocalidade = coSituacaoLocalidade;
	}

	public String getNoSituacaoLocalidade() {
		return noSituacaoLocalidade;
	}

	public void setNoSituacaoLocalidade(String noSituacaoLocalidade) {
		this.noSituacaoLocalidade = noSituacaoLocalidade;
	}

	public String getSgSituacaoLocalidade() {
		return sgSituacaoLocalidade;
	}

	public void setSgSituacaoLocalidade(String sgSituacaoLocalidade) {
		this.sgSituacaoLocalidade = sgSituacaoLocalidade;
	}
}